#!/usr/bin/env bash
#
# check-ai-attribution.sh — falla si un commit o un cuerpo de PR atribuye
# autoría a una IA.
#
# Traído del repo de Fenora, donde nació; las referencias a issues de los
# comentarios son de aquel repo. Las normas que aplica son las de AGENTS.md §6.
# AGENTS.md §6 lo prohíbe; este script es el
# guardarraíl que lo hace cumplir en vez de depender de que cada sesión se
# acuerde. Ver issue #174.
#
#   ./check-ai-attribution.sh --commits <rango-git>   # ej. origin/main..HEAD (DOS puntos: ver issue #411/PR #416, tres cuenta tambien commits de base que HEAD no tiene si la rama esta por detras)
#   ./check-ai-attribution.sh --text <fichero>        # ej. el cuerpo del PR
#   ./check-ai-attribution.sh --clean <fichero>       # imprime el cuerpo sin las líneas prohibidas
#   ./check-ai-attribution.sh --self-test             # demuestra que el check puede fallar
#
# No se prohíbe `Co-authored-by` en general — solo cuando la identidad es
# una IA. Un `Co-authored-by: Andrés Mejía <...>` pasa limpio.
#
# `--clean` es el limpiador del issue #320: reutiliza el MISMO array
# PATTERNS de abajo para reescribir un cuerpo de PR en vez de solo
# juzgarlo, así el limpiador nunca deja pasar algo que este check
# bloquea (o al revés). Sigue siendo un best-effort — el guardarraíl de
# `--text`/`--commits` es la última línea, no este modo.

set -euo pipefail

# patrón → explicación que se imprime cuando salta
#
# Los dos primeros van anclados a principio de línea porque son
# TRAILERS: git solo los reconoce ahí. Sin anclar, el patrón casaba con
# cualquier prosa que los nombrase — y el primer falso positivo real fue
# el commit que introdujo este mismo script, cuyo cuerpo los describe.
# El pie de generación y el emoji sí van sin anclar: en un cuerpo de PR
# pueden aparecer en cualquier posición.
#
# El pie acepta «with» Y «by». No es simetría gratuita: la primera
# versión solo miraba «Generated with», y el servidor MCP que abre los
# PRs estampa «_Generated by [Claude Code](...)_». Se coló entero en el
# cuerpo del PR #179 — el de este mismo guardarraíl — sin que el check
# dijera una palabra.
#
# Efecto secundario asumido: como este patrón NO va anclado, un mensaje
# que cite el pie literalmente salta, aunque solo esté hablando de él.
# Pasó con el commit que arregló esto. No se resuelve debilitando el
# patrón: se resuelve describiendo el pie en vez de reproducirlo. Fallar
# de más aquí es el lado seguro, y la salida cuesta una frase.
PATTERNS=(
  '^[[:space:]]*Co-Authored-By:.*(claude|anthropic|noreply@anthropic\.com)|::atribuye la coautoría del commit a una IA — la autoría es de Andrés Mejía (CLAUDE.md, sección Git)'
  '^[[:space:]]*Claude-Session:|::deja un identificador de sesión de IA en el mensaje — no forma parte del contrato de trazabilidad de AGENTS.md, que es la rama y el PR'
  'Generated[[:space:]]+(with|by)[[:space:]]*\[?Claude[[:space:]]+Code|::pie de "Generated with/by Claude Code" — es la plantilla por defecto de las herramientas de Claude, prohibida por CLAUDE.md'
  '🤖|::emoji de robot en el mensaje — marca visualmente el commit/PR como generado por IA, lo que CLAUDE.md prohíbe'
)

# Identidad (nombre o email) de autor/committer que delata una sesión de IA
# en vez de la cuenta de Andrés — issue #411. Esto es un guardarraíl
# DISTINTO de PATTERNS: PATTERNS juzga el TEXTO del commit/PR, esto juzga
# QUIÉN firma, y son atacables por separado. Los 12 commits que motivaron
# el issue tenían mensajes perfectamente limpios — "fix(ci): ..." sin
# ningún trailer prohibido — y autor/committer `Claude <noreply@anthropic.com>`.
# Un check que solo mira PATTERNS nunca los habría visto.
#
# Ancla a límite de palabra (`[^a-z]` o extremo de cadena) para no casar
# con nombres reales que contienen la subcadena como prefijo de otra
# palabra — "Claudette" o "Claudio" no son "Claude" (self-test:
# fixture-verde-identidad-2).
#
# El ancla corta en LOS DOS sentidos, y solo uno es el lado seguro. Un
# nombre compuesto donde "Claude" aparece como palabra suelta
# ("Jean-Claude Dupont") sí casa — falso positivo aceptado, mismo
# criterio que los patrones sin anclar de arriba: fallar hacia detectar
# de más ahí no cuesta nada real. Pero un SUFIJO alfabético pegado
# ("ClaudeBot", "ClaudeCode", "AnthropicAI", "claudebot@...") desactiva
# el ancla igual que un prefijo, y ahí NO es el lado seguro: una
# identidad de IA real con ese patrón de nombre pasa el check en limpio.
# Hallazgo de la ronda 2 de `reviewer` en el PR #416, sin resolver
# todavía — ver "Qué queda vivo" del AGENT-LOG de ese PR. No se
# resuelve quitando el ancla de cola sin más: eso reintroduce el
# problema que la ronda 1 encontró con "Claudette".
AI_IDENTITY_PATTERN='(^|[^a-z])claude([^a-z]|$)|(^|[^a-z])anthropic([^a-z]|$)'

violations=0

check_text() {
  local source_label="$1"
  local content="$2"
  local pattern explanation line
  for entry in "${PATTERNS[@]}"; do
    # El separador es `|::`, no `::`. Cortar solo por `::` dejaba el `|`
    # pegado al final del patrón, y en ERE `algo|` es una alternancia con
    # el lado derecho vacío: casa con CUALQUIER línea. Con ese fallo el
    # script marcaba como prohibido hasta «fix: corrige el redondeo», y
    # las fixtures rojas daban OK por accidente en vez de por acierto.
    pattern="${entry%%|::*}"
    explanation="${entry#*|::}"
    while IFS= read -r line; do
      [ -z "$line" ] && continue
      echo "::error::${source_label}: línea prohibida — ${explanation}"
      echo "    > ${line}"
      violations=$((violations + 1))
    done < <(printf '%s\n' "$content" | grep -inE "$pattern" || true)
  done
}

# Comprueba un nombre+email de autor/committer contra AI_IDENTITY_PATTERN.
# Separado de check_text porque el dato de entrada es otro (identidad git,
# no texto libre) y porque el mensaje de error tiene que decir qué campo
# (autor/committer) es el que delata, no solo "línea prohibida".
check_identity() {
  local source_label="$1" role="$2" name="$3" email="$4"
  if printf '%s\t%s' "$name" "$email" | grep -qiE "$AI_IDENTITY_PATTERN"; then
    echo "::error::${source_label}: el ${role} es una identidad de IA — ${name} <${email}>. Autor y committer tienen que ser Andrés Mejía (CLAUDE.md, sección Git)."
    violations=$((violations + 1))
  fi
}

run_commits() {
  local range="$1"
  local hash subject body author_name author_email committer_name committer_email
  local hashes stderr_file

  # `hashes="$(...)"` dentro de un `if`, no `done < <(git log ...)`: un
  # rango inválido (rama borrada, `fetch-depth` insuficiente) dentro de
  # una sustitución de proceso no dispara `set -e` ni deja rastro — el
  # bucle simplemente no itera y el check sale "limpio" sin haber mirado
  # nada. Con la asignación en la condición de un `if`, el fallo de
  # `git log` sí se captura y cuenta como violación en vez de pasar en
  # silencio, que para este guardarraíl es el lado seguro: un rango que
  # no se pudo leer no es lo mismo que un rango sin atribución de IA.
  #
  # El stderr de `git log` va a un fichero aparte, NUNCA mezclado con
  # `hashes` (nada de `2>&1` en la misma sustitución): un `git log` que
  # tiene éxito pero escribe un aviso por stderr (p. ej. "warning:
  # refname '...' is ambiguous") contaminaría la lista de hashes con esa
  # línea si compartieran el mismo flujo, y el hash contaminado revienta
  # la iteración de abajo con un error de git opaco, sin ningún
  # `::error::` de atribución que lo explique. Hallazgo de la ronda 2 de
  # `reviewer` en el PR #416.
  stderr_file="$(mktemp)"
  if ! hashes="$(git log --format='%H' "$range" 2>"$stderr_file")"; then
    echo "::error::no se pudo leer el rango de commits \"${range}\": $(cat "$stderr_file")"
    rm -f "$stderr_file"
    violations=$((violations + 1))
    return
  fi
  rm -f "$stderr_file"

  while IFS= read -r hash; do
    [ -z "$hash" ] && continue
    subject="$(git log -1 --format='%s' "$hash")"
    body="$(git log -1 --format='%b' "$hash")"
    check_text "commit ${hash:0:9} (\"${subject}\")" "${subject}"$'\n'"${body}"

    # Autor y committer por separado: un merge de resolución de conflicto
    # puede llevar autor de una identidad y committer de otra, y las dos
    # cuentan igual — son exactamente el tipo de commit que motivó el
    # issue (5 de los 12 eran merges "origin/main into claude/...").
    author_name="$(git log -1 --format='%an' "$hash")"
    author_email="$(git log -1 --format='%ae' "$hash")"
    committer_name="$(git log -1 --format='%cn' "$hash")"
    committer_email="$(git log -1 --format='%ce' "$hash")"
    check_identity "commit ${hash:0:9} (\"${subject}\")" "autor" "$author_name" "$author_email"
    check_identity "commit ${hash:0:9} (\"${subject}\")" "committer" "$committer_name" "$committer_email"
  done <<< "$hashes"
}

run_text() {
  local file="$1"
  check_text "$(basename "$file")" "$(cat "$file")"
}

# Quita del texto cualquier línea que case con un patrón de PATTERNS,
# línea a línea — el mismo criterio que usa check_text, así que lo que
# el check bloquea es exactamente lo que esto borra, ni más ni menos.
#
# Después recorta las líneas finales vacías o el separador "---" que el
# pie deja colgando al desaparecer (el pie de generación del servidor
# MCP siempre lo precede: ver fixture-roja-3). Sin este recorte, un
# cuerpo limpio terminaría con un separador que ya no separa nada.
clean_text() {
  local content="$1"
  local -a out=()
  local line pattern matched entry

  while IFS= read -r line || [ -n "$line" ]; do
    matched=0
    for entry in "${PATTERNS[@]}"; do
      pattern="${entry%%|::*}"
      if printf '%s' "$line" | grep -qiE "$pattern"; then
        matched=1
        break
      fi
    done
    [ "$matched" -eq 0 ] && out+=("$line")
  done <<<"$content"

  local n=${#out[@]}
  local trimmed
  while [ "$n" -gt 0 ]; do
    trimmed="$(printf '%s' "${out[$((n - 1))]}" | sed -E 's/^[[:space:]]+|[[:space:]]+$//g')"
    if [ -z "$trimmed" ] || [ "$trimmed" = "---" ]; then
      n=$((n - 1))
    else
      break
    fi
  done

  local i
  for ((i = 0; i < n; i++)); do
    printf '%s\n' "${out[$i]}"
  done
}

run_clean() {
  local file="$1"
  clean_text "$(cat "$file")"
}

# Comprueba una fixture contra el NÚMERO EXACTO de violaciones esperadas.
#
# El conteo exacto no es pedantería. La primera versión de este self-test
# solo miraba `violations > 0` en los casos rojos, y con un bug que hacía
# casar TODOS los patrones con TODAS las líneas los rojos seguían dando
# OK: 12 violaciones donde había una. Un arnés que solo sabe distinguir
# «alguna» de «ninguna» no detecta el sobre-emparejamiento, que es
# precisamente el fallo que tuvo este script.
assert_violations() {
  local label="$1" esperadas="$2" texto="$3"
  violations=0
  check_text "$label" "$texto"
  if [ "$violations" -ne "$esperadas" ]; then
    echo "SELF-TEST FALLÓ: ${label} esperaba ${esperadas} violación(es) y hubo ${violations}."
    return 1
  fi
  echo "SELF-TEST OK: ${label} → ${violations} violación(es), como se esperaba."
  return 0
}

# Igual que assert_violations, pero para check_identity: fixture de
# autor/committer en vez de texto de mensaje. Van por separado porque
# ejercitan patrones y campos de entrada distintos.
assert_identity() {
  local label="$1" esperadas="$2" role="$3" name="$4" email="$5"
  violations=0
  check_identity "$label" "$role" "$name" "$email"
  if [ "$violations" -ne "$esperadas" ]; then
    echo "SELF-TEST FALLÓ: ${label} esperaba ${esperadas} violación(es) y hubo ${violations}."
    return 1
  fi
  echo "SELF-TEST OK: ${label} → ${violations} violación(es), como se esperaba."
  return 0
}

# Compara clean_text contra el resultado EXACTO esperado, no solo contra
# "ya no hay violaciones" — eso demostraría que --clean puede quedarse
# corto (borra de más) sin que el self-test lo note.
assert_clean() {
  local label="$1" esperado="$2" texto="$3"
  local obtenido
  obtenido="$(clean_text "$texto")"
  if [ "$obtenido" != "$esperado" ]; then
    echo "SELF-TEST FALLÓ: ${label}."
    echo "  esperado: $(printf '%q' "$esperado")"
    echo "  obtenido: $(printf '%q' "$obtenido")"
    return 1
  fi
  echo "SELF-TEST OK: ${label} → limpieza como se esperaba."
  return 0
}

self_test() {
  local fails=0

  # Rojas: exactamente las líneas prohibidas, ni una más.
  assert_violations "fixture-roja (Co-Authored-By de IA)" 1 "fix: ajusta el cálculo de intereses

Co-Authored-By: Claude Sonnet 5 <noreply@anthropic.com>" || fails=1

  # Dos: el pie de generación y el emoji son violaciones distintas.
  assert_violations "fixture-roja-2 (pie de generación + emoji)" 2 \
    "🤖 Generated with [Claude Code](https://claude.ai/code)" || fails=1

  # El pie que estampa el servidor MCP al abrir un PR. Dice «by», no
  # «with», y por eso la primera versión del patrón no lo veía.
  assert_violations "fixture-roja-3 (pie «Generated by» del servidor MCP)" 1 \
    "---
_Generated by [Claude Code](https://claude.ai/code/session_017qRveeyP9VHF1BJCGWmjfY)_" || fails=1

  # Verdes: cero. Una coautoría de persona real NO se rechaza.
  assert_violations "fixture-verde (coautoría de persona real)" 0 "feat: añade el simulador de deudas

Co-authored-by: Andrés Mejía <49398769+andres-mejia@users.noreply.github.com>" || fails=1

  assert_violations "fixture-verde-2 (commit normal)" 0 \
    "fix: corrige el redondeo de céntimos en el simulador" || fails=1

  # Verde-3: PROSA que NOMBRA los trailers sin usarlos. Es el falso
  # positivo que este script tuvo de verdad — el cuerpo del commit que lo
  # introdujo describe lo que prohíbe. Sin el ancla `^`, aquí saltaban dos
  # violaciones donde no hay ninguna atribución. Esta fixture es lo que
  # impide que alguien quite el ancla «porque no hace falta».
  assert_violations "fixture-verde-3 (prosa que nombra los trailers)" 0 \
    "chore: añade el guardarraíl de atribución

El script rechaza los trailers Co-Authored-By: Claude y Claude-Session:,
que CLAUDE.md prohíbe en la sección Git." || fails=1

  # Fixtures de identidad — issue #411. El caso real: los 12 commits en
  # `main` tenían mensaje limpio (arriba, fixture-verde-3 lo demuestra) Y
  # autor/committer `Claude <noreply@anthropic.com>`. Esta fixture es la
  # mutación en rojo que pide el issue: antes de check_identity, nada de
  # esto se detectaba porque check_text nunca mira el autor.
  assert_identity "fixture-roja-identidad (autor Claude)" 1 \
    "autor" "Claude" "noreply@anthropic.com" || fails=1

  assert_identity "fixture-roja-identidad-2 (committer claude, minúsculas)" 1 \
    "committer" "claude" "noreply@anthropic.com" || fails=1

  # El nombre visible en los co-authors trailers de Claude Code
  # ("Claude Sonnet 5", "Claude Opus 5", ...) tiene que casar igual: la
  # coma/versión detrás de "Claude" no debe romper el ancla de palabra.
  assert_identity "fixture-roja-identidad-3 (nombre con versión de modelo)" 1 \
    "autor" "Claude Sonnet 5" "noreply@anthropic.com" || fails=1

  # Email de un dominio de Anthropic con nombre humano — el nombre solo no
  # basta como guardarraíl si el email delata la cuenta de servicio.
  assert_identity "fixture-roja-identidad-4 (email @anthropic.com, nombre humano)" 1 \
    "committer" "Bot de Despliegue" "ci@anthropic.com" || fails=1

  # Verde: la identidad real de Andrés no debe dispararlo.
  assert_identity "fixture-verde-identidad (Andrés Mejía)" 0 \
    "autor" "Andrés Mejía" "49398769+andres-mejia@users.noreply.github.com" || fails=1

  # Verde-2: "Claudette" SÍ contiene la subcadena "claude" como prefijo
  # ("Claude" + "tte") — a propósito, para que esta fixture pruebe algo
  # de verdad. "Claudia" (usada en una versión anterior de esta fixture)
  # no vale: ni siquiera contiene la subcadena ("Claud" + "ia", sin la
  # "e"), así que pasaba en verde con o sin el ancla y no demostraba
  # nada — hallazgo de `reviewer` en el PR #416, reproducido quitando el
  # ancla del patrón y viendo que el self-test seguía entero en verde.
  # Con "Claudette" sí se nota: sin el ancla de palabra, esta fixture
  # rompe (pasaría a marcar 1 violación en vez de 0).
  assert_identity "fixture-verde-identidad-2 (Claudette, no Claude)" 0 \
    "autor" "Claudette Martin" "claudette.martin@example.com" || fails=1

  # --clean: el caso que motiva el issue #320 — el pie que la propia
  # herramienta añade al cuerpo del PR, con el separador que queda
  # colgando al quitarlo. Debe desaparecer entero, sin dejar rastro.
  assert_clean "limpieza (pie de generación + separador colgando)" \
    "Cierra el issue #320: reutiliza los patrones del guardarraíl." \
    "Cierra el issue #320: reutiliza los patrones del guardarraíl.

---
🤖 Generated with [Claude Code](https://claude.com/claude-code)" || fails=1

  # --clean con el pie exacto del servidor MCP (fixture-roja-3): el
  # cuerpo entero era el pie, así que limpio es vacío.
  assert_clean "limpieza (pie «Generated by» del servidor MCP, cuerpo vacío tras limpiar)" \
    "" \
    "---
_Generated by [Claude Code](https://claude.ai/code/session_017qRveeyP9VHF1BJCGWmjfY)_" || fails=1

  # --clean NUNCA toca una coautoría de persona real — es la demostración
  # explícita que pide el issue #320: el limpiador puede fallar (borrar
  # de más) si algún día alguien le quita el ancla `^` a PATTERNS, y este
  # caso es lo que lo detectaría.
  assert_clean "limpieza (coautoría de persona real, intacta)" \
    "feat: añade el simulador de deudas

Co-authored-by: Andrés Mejía <49398769+andres-mejia@users.noreply.github.com>" \
    "feat: añade el simulador de deudas

Co-authored-by: Andrés Mejía <49398769+andres-mejia@users.noreply.github.com>" || fails=1

  violations=0
  return $fails
}

usage() {
  echo "Uso: $0 --commits <rango-git> | --text <fichero> | --clean <fichero> | --self-test" >&2
  exit 2
}

[ $# -ge 1 ] || usage

case "$1" in
  --commits)
    [ $# -eq 2 ] || usage
    run_commits "$2"
    ;;
  --text)
    [ $# -eq 2 ] || usage
    run_text "$2"
    ;;
  --clean)
    # Modo sin veredicto: imprime el texto limpio y sale. No pasa por el
    # contador `violations` de abajo — limpiar no es juzgar, y este modo
    # nunca debe hacer fallar un paso de CI por sí solo.
    [ $# -eq 2 ] || usage
    run_clean "$2"
    exit 0
    ;;
  --self-test)
    self_test
    exit $?
    ;;
  *)
    usage
    ;;
esac

if [ "$violations" -gt 0 ]; then
  echo "::error::${violations} línea(s) con atribución de IA. Corrige el mensaje y vuelve a pushear."
  exit 1
fi

echo "Sin atribución de IA detectada."
